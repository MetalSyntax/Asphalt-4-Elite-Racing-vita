#!/usr/bin/env python3
"""Writes docs/imports.md: every import of decompiled/macho/imports.txt -> shim file -> status.

Status: real (implemented / mapped to newlib, vitaGL, openal-soft, libstdc++), stub (deliberate
offline/no-op shim, logged where it matters), class (ObjC host class created on demand by
objc_import_lookup), const (NSString constant), MISSING (would bind to the [UNIMPL] logging stub).

Usage: python3 -I tools/imports_table.py   (prints the counts; exit 1 if anything is MISSING)
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Implementations that intentionally do nothing useful (offline network, no rumble, IGP store...).
STUBS = {
    'd_ok', 'd_zero', 'd_null', 'd_net_fail', 'd_getaddrinfo', 'd_gethostbyname', 'd_select', 'audio_fail',
    'aq_unimpl', 'as_play_system_sound', 'al_mixer_output_rate', 'cf_null', 'sc_fail', 'sc_null_ptr',
    'sc_null', 'sc_reachability_flags', 'cg_draw_image', 'objc_noop', 'ok', 'cg_noop', 'g_glNoop',
    'd_sjlj_noop', 'cxx_personality_sj0', 'd_inet_ntoa',
}

imports = [l.strip() for l in open(os.path.join(ROOT, 'decompiled/macho/imports.txt')) if l.strip()]
provided = {}  # import name -> (file, impl)
consts = set()
for path in sorted(glob.glob(os.path.join(ROOT, 'source', '*.[ch]'))):
    base = os.path.basename(path)
    if base.startswith('._'):
        continue
    src = open(path, errors='ignore').read()
    for m in re.finditer(r'\b(F|D|V)\(\s*([A-Za-z_$][\w$]*)\s*(?:,\s*([&\w]+))?', src):
        kind, name, impl = m.groups()
        impl = impl or name
        provided.setdefault('_' + name, (base, impl if kind != 'D' else 'direct:' + name))
    for m in re.finditer(r'F_RAW\(\s*"(_[\w$]+)"\s*,\s*(\w+)', src):
        provided.setdefault(m.group(1), (base, m.group(2)))
    for m in re.finditer(r'\{\s*"(_[\w$]+)"\s*,\s*\(uintptr_t\)&?(\w+)', src):
        provided.setdefault(m.group(1), (base, m.group(2)))
    if base == 'objc.c':
        block = src[src.index('const_names[] = {'):]
        block = block[:block.index('};')]
        consts.update('_' + c for c in re.findall(r'"(\w+)"', block))

rows, counts = [], {}
for name in imports:
    if name.startswith(('_OBJC_CLASS_$_', '_OBJC_METACLASS_$_')):
        st, f, impl = 'class', 'objc.c / uikit.c', 'objc_import_lookup (host class)'
    elif name == '___CFConstantStringClassReference':
        st, f, impl = 'real', 'objc.c', 'NSString class'
    elif name in consts:
        st, f, impl = 'const', 'objc.c', 'const_names (NSString)'
    elif name in provided:
        f, impl = provided[name]
        st = 'stub' if impl in STUBS else 'real'
    else:
        st, f, impl = 'MISSING', '-', '[UNIMPL] logging stub'
    counts[st] = counts.get(st, 0) + 1
    rows.append(f'| `{name}` | {f} | {impl} | {st} |')

with open(os.path.join(ROOT, 'docs', 'imports.md'), 'w') as out:
    out.write('# Asphalt 4 imports -> shims\n\n')
    out.write('Generated by `python3 -I tools/imports_table.py` from `decompiled/macho/imports.txt` '
              f'({len(imports)} imports) and the import tables in `source/`.\n\n')
    out.write('Totals: ' + ', '.join(f'{k} {v}' for k, v in sorted(counts.items())) + '\n\n')
    out.write('Status: **real** = implemented or mapped to newlib/vitaGL/openal-soft/libstdc++; **stub** = '
              'deliberate no-op/offline shim; **class** = ObjC host class; **const** = NSString constant; '
              '**MISSING** = binds to the `[UNIMPL]` logging stub.\n\n')
    out.write('| Import | Shim file | Implementation | Status |\n|---|---|---|---|\n')
    out.write('\n'.join(rows) + '\n')
print(' '.join(f'{k}={v}' for k, v in sorted(counts.items())), f'total={len(imports)}')
sys.exit(1 if counts.get('MISSING') else 0)
